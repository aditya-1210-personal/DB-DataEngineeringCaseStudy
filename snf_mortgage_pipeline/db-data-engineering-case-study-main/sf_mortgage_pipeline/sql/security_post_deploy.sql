-- After dbt build; assumes models are deployed into MORTGAGE_DB.STAGE.
CREATE MASKING POLICY IF NOT EXISTS MORTGAGE_DB.STAGE.PII_MASK_POLICY
AS (VAL STRING) RETURNS STRING ->
 CASE WHEN IS_ROLE_IN_SESSION('COMPLIANCE_OFFICER') THEN VAL ELSE '***MASKED***' END;
ALTER TABLE MORTGAGE_DB.STAGE.CLEAN_APPLICATIONS
 MODIFY COLUMN APPLICANT_NAME SET MASKING POLICY MORTGAGE_DB.STAGE.PII_MASK_POLICY;
ALTER TABLE MORTGAGE_DB.STAGE.CLEAN_APPLICATIONS
 MODIFY COLUMN SSN SET MASKING POLICY MORTGAGE_DB.STAGE.PII_MASK_POLICY;
