CREATE DATABASE IF NOT EXISTS MORTGAGE_DB;
CREATE WAREHOUSE IF NOT EXISTS MORTGAGE_WH WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.CURATED;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.STAGE;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.RAW;
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.RAW.MORTGAGE_APPLICATIONS_RAW (
 APPLICATION_ID STRING, APPLICANT_ID STRING, PAYLOAD VARIANT, SOURCE_FILE STRING,
 INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.RAW.CREDIT_BUREAU_RAW (
 APPLICANT_ID STRING, SSN STRING, FICO_SCORE NUMBER(3,0), MONTHLY_DEBT NUMBER(14,2),
 SOURCE_FILE STRING, INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP());
